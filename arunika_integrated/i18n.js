  function detect() {
    try { var s = localStorage.getItem(KEY); if (s === 'id' || s === 'en') return s; } catch (e) {}
    var n = ((navigator.languages && navigator.languages[0]) || navigator.language || 'id').toLowerCase();
    return n.indexOf('en') === 0 ? 'en' : 'id';
  }

  var I18N = { lang: detect(), dict: DICT };

  I18N.t = function (key, params, fallback) {
    var d = DICT[I18N.lang] || {};
    var s = d[key];
    if (s == null) s = (DICT.id || {})[key];
    if (s == null) s = fallback != null ? fallback : key;
    if (params) s = s.replace(/\{(\w+)\}/g, function (m, k) { return params[k] != null ? params[k] : m; });
    return s;
  };

  I18N.apply = function (root) {
    root = root || document;
    var nodes = root.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i], v = I18N.t(el.getAttribute('data-i18n'), null, null);
      if (v == null || v === el.getAttribute('data-i18n')) continue;
      if (/[<&]/.test(v)) el.innerHTML = v; else el.textContent = v;
    }
    var attrs = root.querySelectorAll('[data-i18n-attr]');
    for (var j = 0; j < attrs.length; j++) {
      attrs[j].getAttribute('data-i18n-attr').split(';').forEach(function (pair) {
        var p = pair.split(':'); if (p.length < 2) return;
        var v = I18N.t(p[1].trim(), null, null);
        if (v != null && v !== p[1].trim()) attrs[j].setAttribute(p[0].trim(), v);
      });
    }
  };

  I18N.setLang = function (lang, silent) {
    if (lang !== 'id' && lang !== 'en') lang = 'id';
    I18N.lang = lang;
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    document.documentElement.lang = lang;
    I18N.apply(document);
    var btns = document.querySelectorAll('.lang-btn[data-lang]');
    for (var i = 0; i < btns.length; i++) btns[i].setAttribute('aria-pressed', String(btns[i].getAttribute('data-lang') === lang));
    if (!silent) window.dispatchEvent(new CustomEvent('arunika:lang', { detail: { lang: lang } }));
  };

  I18N.init = function () {
    document.documentElement.lang = I18N.lang;
    I18N.apply(document);
    var btns = document.querySelectorAll('.lang-btn[data-lang]');
    for (var i = 0; i < btns.length; i++) {
      btns[i].setAttribute('aria-pressed', String(btns[i].getAttribute('data-lang') === I18N.lang));
      btns[i].addEventListener('click', function (e) {
        var l = e.currentTarget.getAttribute('data-lang');
        if (l !== I18N.lang) I18N.setLang(l);
      });
    }
  };

  window.I18N = I18N;
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', I18N.init); else I18N.init();
